import type {
  DiagramEdge,
  DiagramNode,
  LayerKey,
  ManualThreat,
  Severity,
  ThreatView,
} from '../../core/model/types';
import { isSuppressed } from '../../core/model/types';
import type { TranslationKey } from '../../i18n';
import { TM7_PRODUCT } from './tm7ToProject';

/**
 * 移行レポート：Microsoft Threat Modeling Tool から取り込んだ脅威と、CyberRiskScape が検出した脅威の重なりと差。
 *
 * 突き合わせの単位は「同じ要素 × 同じ STRIDE の分類」。TMT の脅威はデータフローに付くので、その線と両端のノードに
 * 当たった検出脅威を候補にする。TMT の脅威は STRIDE の汎用の問いで、CyberRiskScape のルールとは 1 対 1 に
 * 対応しないため、名前では照合しない（重なりは「同じ問いに具体的な脅威が当たっている」ことを示すだけ）。
 * 判定（脅威があるか）は既存の脅威エンジンに任せ、ここは並べ替えるだけ。
 */

export interface MigrationLayerInput {
  layer: LayerKey;
  /** framework は ALL で作ったビュー（手動脅威と検出脅威の両方を含む）。 */
  threats: ThreatView[];
  nodes: DiagramNode[];
  edges: DiagramEdge[];
}

export interface MigrationThreatRef {
  layer: LayerKey;
  id: string;
  title: string;
  category: string;
  severity: Severity;
  /** 対象の表示名（線は「始点 → 終点：線の名前」）。 */
  target: string;
  suppressed: boolean;
  assumed: boolean;
}

export interface TmtEntry extends MigrationThreatRef {
  tmtId: string;
  tmtTypeId: string;
  /** TMT の STRIDE の分類（UserThreatCategory）。 */
  tmtCategory: string;
  /** TMT での状態（読み替える前の値）。 */
  tmtState: string;
  tmtChangedBy?: string;
  /** 同じ要素・同じ分類で CyberRiskScape が検出した脅威。 */
  matches: MigrationThreatRef[];
}

export interface MigrationReport {
  tmt: {
    total: number;
    /** 状態 → 件数（Mitigated / NotApplicable / NeedsInvestigation / AutoGenerated 等、元の値）。 */
    byState: Record<string, number>;
  };
  detected: {
    total: number;
    bySeverity: Record<Severity, number>;
    /** 未入力の属性を悪い値と仮定して出た件数。 */
    assumed: number;
    /** STRIDE 以外（AI・エージェント）の件数。 */
    beyondStride: number;
  };
  entries: TmtEntry[];
  /** TMT で対策済み・対象外としたのに、同じ要素・分類で抑制されていない検出脅威がある（判断の見直し候補）。 */
  recheck: TmtEntry[];
  /** どの TMT の脅威とも重ならない検出脅威（CyberRiskScape が足したもの）。重大度の高い順。 */
  detectedOnly: (MigrationThreatRef & { framework: string })[];
}

const SEVERITY_ORDER: Severity[] = ['Critical', 'High', 'Medium', 'Low'];
const CLOSED_STATES = new Set(['Mitigated', 'NotApplicable']);

/** STRIDE の分類名を比べられる形に（'Elevation Of Privilege' と 'Elevation of Privilege' を同一視、'Spoofing/Tampering' は両方）。 */
function strideKeys(category: string): Set<string> {
  return new Set(
    category
      .split('/')
      .map((c) => c.toLowerCase().replace(/[^a-z]/g, ''))
      .filter((c) => c !== ''),
  );
}

export function buildMigrationReport(input: {
  layers: MigrationLayerInput[];
  manualThreats: Record<LayerKey, ManualThreat[]>;
}): MigrationReport {
  const byState: Record<string, number> = {};
  const bySeverity: Record<Severity, number> = { Critical: 0, High: 0, Medium: 0, Low: 0 };
  const entries: TmtEntry[] = [];
  const matchedDetected = new Set<string>();
  const detectedAll: (MigrationThreatRef & { framework: string; subjectKeys: string[]; stride: Set<string> })[] = [];
  let assumed = 0;
  let beyondStride = 0;

  for (const l of input.layers) {
    // 同じ名前の要素を区別できるよう、画面と同じ表示 ID（C{seq}・DF{seq}）を前に付ける。
    const nodeLabel = new Map(l.nodes.map((n) => [n.id, `${n.seq ? `C${n.seq} ` : ''}${n.label ?? n.type}`]));
    const edgeById = new Map(l.edges.map((e) => [e.id, e]));
    const edgeLabel = (e: DiagramEdge) =>
      `${e.seq ? `DF${e.seq} ` : ''}${nodeLabel.get(e.source) ?? e.source} → ${nodeLabel.get(e.target) ?? e.target}${e.dataFlowName ? `：${e.dataFlowName}` : ''}`;
    const targetOf = (t: ThreatView): string => {
      if (t.subject?.kind === 'edge') {
        const e = edgeById.get(t.subject.id);
        if (e) return edgeLabel(e);
      }
      return nodeLabel.get(t.subject?.id ?? t.nodeId) ?? nodeLabel.get(t.nodeId) ?? '';
    };
    const ref = (t: ThreatView): MigrationThreatRef => ({
      layer: l.layer,
      id: t.id,
      title: t.origin === 'manual' ? t.category : (t.name ?? t.category),
      category: t.category,
      severity: t.severity,
      target: targetOf(t),
      suppressed: isSuppressed(t),
      assumed: (t.assumptionFlags?.length ?? 0) > 0,
    });

    for (const t of l.threats) {
      if (t.origin !== 'detected') continue;
      const r = ref(t);
      bySeverity[t.severity] += 1;
      if (r.assumed) assumed += 1;
      if (t.framework !== 'STRIDE') beyondStride += 1;
      const keys = [t.subject ? `${t.subject.kind}:${t.subject.id}` : `node:${t.nodeId}`];
      detectedAll.push({ ...r, framework: t.framework, subjectKeys: keys, stride: strideKeys(t.category) });
    }

    const manualById = new Map(input.manualThreats[l.layer].map((m) => [m.id, m]));
    for (const t of l.threats) {
      if (t.origin !== 'manual' || !t.manualId) continue;
      const m = manualById.get(t.manualId);
      if (!m?.importedFrom || m.importedFrom.product !== TM7_PRODUCT) continue;
      const f = m.importedFrom.fields;
      const state = f.State ?? '';
      byState[state] = (byState[state] ?? 0) + 1;
      const keys = new Set<string>();
      if (t.subject?.kind === 'edge') {
        keys.add(`edge:${t.subject.id}`);
        const e = edgeById.get(t.subject.id);
        if (e) {
          keys.add(`node:${e.source}`);
          keys.add(`node:${e.target}`);
        }
      } else if (t.nodeId) {
        keys.add(`node:${t.nodeId}`);
      }
      const tmtCategory = f.UserThreatCategory ?? t.category;
      const stride = strideKeys(tmtCategory);
      const matches = detectedAll.filter(
        (d) => d.layer === l.layer && d.subjectKeys.some((k) => keys.has(k)) && [...d.stride].some((s) => stride.has(s)),
      );
      for (const d of matches) matchedDetected.add(`${d.layer}:${d.id}`);
      entries.push({
        ...ref(t),
        tmtId: m.importedFrom.externalId,
        tmtTypeId: f.TypeId ?? '',
        tmtCategory,
        tmtState: state,
        ...(f.ChangedBy ? { tmtChangedBy: f.ChangedBy } : {}),
        matches: matches.map(({ framework: _f, subjectKeys: _k, stride: _s, ...rest }) => rest),
      });
    }
  }

  const rank = (s: Severity) => SEVERITY_ORDER.indexOf(s);
  const detectedOnly = detectedAll
    .filter((d) => !matchedDetected.has(`${d.layer}:${d.id}`) && !d.suppressed)
    .sort((a, b) => rank(a.severity) - rank(b.severity))
    .map(({ subjectKeys: _k, stride: _s, ...rest }) => rest);

  return {
    tmt: { total: entries.length, byState },
    detected: { total: detectedAll.length, bySeverity, assumed, beyondStride },
    entries,
    recheck: entries.filter((e) => CLOSED_STATES.has(e.tmtState) && e.matches.some((m) => !m.suppressed)),
    detectedOnly,
  };
}

type T = (key: TranslationKey, params?: Record<string, string | number>) => string;

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** Markdown に描く（文言は i18n。`migration.*`）。 */
export function renderMigrationReportMarkdown(r: MigrationReport, t: T): string {
  const out: string[] = [];
  out.push(t('migration.heading'), '', t('migration.intro'), '');

  out.push(t('migration.summary.heading'), '');
  const states = Object.entries(r.tmt.byState)
    .map(([s, n]) => `${s} ${n}`)
    .join(' / ');
  out.push(t('migration.summary.tmt', { total: r.tmt.total, states: states || '-' }));
  out.push(
    t('migration.summary.detected', {
      total: r.detected.total,
      critical: r.detected.bySeverity.Critical,
      high: r.detected.bySeverity.High,
      medium: r.detected.bySeverity.Medium,
      low: r.detected.bySeverity.Low,
    }),
  );
  const covered = r.entries.filter((e) => e.matches.length > 0).length;
  out.push(t('migration.summary.covered', { covered, total: r.tmt.total }));
  out.push(t('migration.summary.detectedOnly', { count: r.detectedOnly.length, beyond: r.detected.beyondStride }));
  out.push(t('migration.summary.assumed', { count: r.detected.assumed }));
  out.push(t('migration.summary.recheck', { count: r.recheck.length }), '');

  out.push(t('migration.recheck.heading'), '', t('migration.recheck.intro'), '');
  if (r.recheck.length === 0) {
    out.push(t('migration.none'), '');
  } else {
    out.push(t('migration.recheck.columns'), '|---|---|---|---|---|');
    for (const e of r.recheck) {
      const open = e.matches.filter((m) => !m.suppressed).map((m) => `${m.title}（${m.severity}）`).join('<br>');
      out.push(`| ${cell(e.tmtId)} | ${cell(e.title)} | ${cell(e.tmtState)}${e.tmtChangedBy ? `（${cell(e.tmtChangedBy)}）` : ''} | ${cell(e.target)} | ${cell(open)} |`);
    }
    out.push('');
  }

  out.push(t('migration.entries.heading'), '', t('migration.entries.intro'), '');
  out.push(t('migration.entries.columns'), '|---|---|---|---|---|---|');
  for (const e of r.entries) {
    const m = e.matches.length > 0 ? e.matches.map((x) => `${x.title}（${x.severity}）`).join('<br>') : t('migration.entries.noMatch');
    out.push(`| ${cell(e.tmtId)} | ${cell(e.title)} | ${cell(e.tmtCategory)} | ${cell(e.tmtState)} | ${cell(e.target)} | ${cell(m)} |`);
  }
  out.push('');

  out.push(t('migration.detectedOnly.heading'), '', t('migration.detectedOnly.intro'), '');
  if (r.detectedOnly.length === 0) {
    out.push(t('migration.none'), '');
  } else {
    out.push(t('migration.detectedOnly.columns'), '|---|---|---|---|---|');
    for (const d of r.detectedOnly) {
      out.push(`| ${d.severity} | ${cell(d.title)} | ${cell(d.framework)} | ${cell(d.target)} | ${d.assumed ? t('migration.assumedMark') : ''} |`);
    }
    out.push('');
  }

  out.push(t('migration.next.heading'), '', t('migration.next.body'), '');
  return out.join('\n');
}
