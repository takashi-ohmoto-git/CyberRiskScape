import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { analyzeProject } from '../../cli/analyze';
import { translate } from '../../i18n';
import { resolveManualThreats } from '../persistence/serialize';
import type { PersistedProject } from '../persistence/schema';
import { buildMigrationReport, renderMigrationReportMarkdown } from './migrationReport';
import { tm7ToProject } from './tm7ToProject';

const XML = readFileSync(new URL('./__fixtures__/example.tm7', import.meta.url), 'utf8');

function imported(): PersistedProject {
  const r = tm7ToProject(XML, { now: 0 });
  if (!r.ok) throw new Error(r.error);
  return r.project;
}

function report(project: PersistedProject) {
  const layers = analyzeProject(project, { framework: 'ALL' }).map((l) => ({
    layer: l.layer,
    threats: l.threats,
    nodes: l.input.nodes,
    edges: l.input.edges,
  }));
  return buildMigrationReport({ layers, manualThreats: resolveManualThreats(project) });
}

describe('buildMigrationReport', () => {
  it('TMT の脅威を全件、元の状態の件数とともに数える', () => {
    const r = report(imported());
    expect(r.tmt.total).toBe(3);
    expect(r.tmt.byState).toEqual({ Mitigated: 1, NeedsInvestigation: 1, AutoGenerated: 1 });
    expect(r.entries.map((e) => e.tmtId).sort()).toEqual(['1', '2', '3']);
  });

  it('同じ要素（線とその両端）・同じ STRIDE の分類の検出脅威だけを重なりにする', () => {
    const r = report(imported());
    for (const e of r.entries) {
      for (const m of e.matches) {
        expect(m.category.toLowerCase().replace(/[^a-z/]/g, '')).toContain(e.tmtCategory.toLowerCase().replace(/[^a-z]/g, ''));
      }
    }
    // Place order（利用者 → ポータル）のなりすましには、同じ線か両端のなりすましが当たる
    const spoof = r.entries.find((e) => e.tmtId === '1')!;
    expect(spoof.matches.length).toBeGreaterThan(0);
  });

  it('TMT で対策済みとしたのに未抑制の検出脅威が重なるものを、判断の見直し候補にする（変更者つき）', () => {
    const r = report(imported());
    const ids = r.recheck.map((e) => e.tmtId);
    expect(ids).toContain('1');
    expect(ids).not.toContain('2'); // NeedsInvestigation は対象外
    expect(r.recheck.find((e) => e.tmtId === '1')?.tmtChangedBy).toBe('EXAMPLE\\alice');
  });

  it('どの TMT の脅威とも重ならない検出脅威を、重大度の高い順に出す', () => {
    const r = report(imported());
    expect(r.detectedOnly.length).toBeGreaterThan(0);
    const order = ['Critical', 'High', 'Medium', 'Low'];
    const ranks = r.detectedOnly.map((d) => order.indexOf(d.severity));
    expect([...ranks].sort((a, b) => a - b)).toEqual(ranks);
    const matchedIds = new Set(r.entries.flatMap((e) => e.matches.map((m) => m.id)));
    expect(r.detectedOnly.some((d) => matchedIds.has(d.id))).toBe(false);
  });

  it('TMT 由来でない手動脅威は数えない', () => {
    const p = imported();
    p.manualThreats!.L1.push({ id: 'own', framework: 'STRIDE', category: 'x', severity: 'Low', description: 'd' });
    expect(report(p).tmt.total).toBe(3);
  });
});

describe('renderMigrationReportMarkdown', () => {
  it.each(['ja', 'en'] as const)('%s: 5 章の見出しと TMT の ID を出す', (locale) => {
    const md = renderMigrationReportMarkdown(report(imported()), (k, p) => translate(k, locale, p));
    expect(md.match(/^## /gm)).toHaveLength(5);
    expect(md).toContain('| 1 |');
    expect(md).toContain('EXAMPLE\\alice');
  });
});
