/**
 * CLI の引数定義（`parseArgs` の options）と、その値の型 `CliValues`。
 */
import { parseArgs } from 'node:util';

/** `parseArgs` の呼び出しを切り出す（options リテラルを直接渡して戻り値の型を具体化するため）。 */
export function parseCliArgs() {
  return parseArgs({
    args: process.argv.slice(2),
    allowPositionals: true,
    strict: true,
    options: {
      format: { type: 'string' },
      layer: { type: 'string' },
      framework: { type: 'string' },
      'fail-on': { type: 'string' },
      'fail-on-action': { type: 'boolean' },
      'fail-on-findings': { type: 'string' },
      'changed-from': { type: 'string' },
      id: { type: 'string' },
      'as-of': { type: 'string' },
      triggers: { type: 'string' },
      locale: { type: 'string' },
      tool: { type: 'string' },
      out: { type: 'string', short: 'o' },
      dashboard: { type: 'string' },
      ocsf: { type: 'string' },
      in: { type: 'string' },
      map: { type: 'string' },
      services: { type: 'string' },
      endpoints: { type: 'string' },
      assets: { type: 'string', multiple: true },
      report: { type: 'string' },
      root: { type: 'string' },
      vars: { type: 'string' },
      veracode: { type: 'string' },
      'skill-scanner': { type: 'string' },
      'mcp-scanner': { type: 'string' },
      evidence: { type: 'string', multiple: true },
      hosts: { type: 'string' },
      sbom: { type: 'string' },
      sarif: { type: 'string' },
      ledger: { type: 'string' },
      kev: { type: 'string' },
      epss: { type: 'string' },
      'epss-threshold': { type: 'string' },
      'dry-run': { type: 'boolean' },
      previous: { type: 'string' },
      'max-age-days': { type: 'string' },
      attacker: { type: 'string' },
      ip: { type: 'string' },
      host: { type: 'string' },
      purl: { type: 'string' },
      node: { type: 'string' },
      xml: { type: 'string' },
      'host-node': { type: 'string', multiple: true },
      'map-value': { type: 'string', multiple: true },
      km: { type: 'string' },
      record: { type: 'string' },
      'system-field': { type: 'string' },
      process: { type: 'string' },
      'process-field': { type: 'string' },
      'value-field': { type: 'string' },
      'cases-field': { type: 'string' },
      currency: { type: 'string' },
      period: { type: 'string' },
      'base-url': { type: 'string' },
      author: { type: 'string' },
      'include-threats': { type: 'boolean' },
      'with-findings': { type: 'boolean' },
      api: { type: 'string' },
      project: { type: 'string' },
      'project-id': { type: 'string' },
      'task-id': { type: 'string' },
      search: { type: 'string' },
      scope: { type: 'string' },
      into: { type: 'string' },
      product: { type: 'string' },
      name: { type: 'string' },
      repo: { type: 'string' },
      path: { type: 'string' },
      since: { type: 'string' },
      'max-commits': { type: 'string' },
      weights: { type: 'string' },
      kind: { type: 'string' },
      category: { type: 'string' },
      'show-secrets': { type: 'boolean' },
      'ca-node': { type: 'string' },
      'idp-node': { type: 'string' },
      'cloud-node': { type: 'string' },
      'vault-node': { type: 'string' },
      'tenant-id': { type: 'string' },
      graph: { type: 'boolean' },
      'print-queries': { type: 'boolean' },
      help: { type: 'boolean' },
    },
  });
}

export type CliValues = ReturnType<typeof parseCliArgs>['values'];
